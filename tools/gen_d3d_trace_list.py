"""Write app/src/bo2zm_d3d_trace_list.inc: the functions bo2zm_d3d_trace.cpp wraps.

Picked from the code index (tools/inspect/gen_index.py build):
  - every function in the XDK Direct3D range that code outside the range calls (its public API),
  - every function in the range that reserves ring space (calls sub_82161700), i.e. writes PM4 packets, and
  - every render-state and sampler-state setter in D3D's setter tables. The device calls them through
    the copies it keeps at device+64+State / +468+State (sub_8217A3E0), so the static call graph misses the ones
    the game only reaches that way. Tables, from the decrypted image: render states 0..400 at 0x82A9F618, sampler
    states 0..76 at 0x82A9FAD8, 12-byte entries {getter, setter, default}.
Range 0x82160000-0x82190000: Swap (sub_821715A8, calls VdSwap) and the device/ring setup
(sub_82161EA8, calls VdInitializeRingBuffer) are inside it. Re-run after a codegen change.
Functions hooked elsewhere are left out (two hooks on one function collide at link time): the D3D state marker's
dump helpers, VS fetch patcher and shader registration (app/src/bo2zm_d3d_marker.cpp). So the trace's shader
registration check no longer runs.
"""
import json, os, struct
ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
fns = json.load(open(os.path.join(ROOT, "work", "gen_index.json")))
LO, HI, RESERVE = 0x82160000, 0x82190000, "82161700"
IMAGE, IMAGE_BASE = os.path.join(ROOT, "work", "dump_tu18", "default_mp.image.bin"), 0x82000000
SETTER_TABLES = [(0x82A9F618, 101), (0x82A9FAD8, 20)]  # (address, entries)
NO_OP_SETTER = "82685BF8"  # render states 0-36
HOOKED_ELSEWHERE = {"82174F38", "82175178", "821752D0", "82175420", "82169BF8", "821698D8"}
inside = lambda n: LO <= int(n, 16) < HI
reserve_callers = set(fns[RESERVE]["callers"])
image = open(IMAGE, "rb").read()
setters = set()
for table, entries in SETTER_TABLES:
    for i in range(entries):
        at = table + 12 * i + 4 - IMAGE_BASE
        setter = "%08X" % struct.unpack(">I", image[at:at + 4])[0]
        if setter != NO_OP_SETTER and inside(setter) and setter in fns:
            setters.add(setter)
picked = []
for n in sorted(fns):
    if not inside(n) or n in HOOKED_ELSEWHERE:
        continue
    ext = [c for c in fns[n]["callers"] if not inside(c)]
    if ext or n in reserve_callers or n in setters:
        picked.append(n)
out = os.path.join(ROOT, "app", "src", "bo2zm_d3d_trace_list.inc")
with open(out, "w", newline="\n") as f:
    f.write("// Generated by tools/gen_d3d_trace_list.py; do not edit. X(address)\n")
    for n in picked:
        f.write(f"X({n})\n")
print(len(picked), "functions ->", out, f"({len(setters)} state setters)")
